/* Bundles the research data (afya-showroom/data/*.json) into showroom/sections/data.js as window.AFYA_DATA,
   so the published page carries it without loading files at runtime. Run after any data change:
   node tools/build-data.js */
const fs=require('fs'),path=require('path');
const D=path.join(__dirname,'..','..','data');
const read=f=>{try{return JSON.parse(fs.readFileSync(path.join(D,f),'utf8'))}catch(e){if(fs.existsSync(path.join(D,f)))throw new Error(f+': '+e.message);return null}};
const out={boxes:{},services:read('services.json')||[],nutrition:read('nutrition.json')||[],built:new Date().toISOString().slice(0,10)};
const bdir=path.join(D,'boxes');
for(const f of fs.readdirSync(bdir).filter(f=>f.endsWith('.json'))){const b=read('boxes/'+f);out.boxes[b.slug]=b}
const js='/* generated by tools/build-data.js from afya-showroom/data — do not edit by hand */\nwindow.AFYA_DATA='+JSON.stringify(out)+';\n';
fs.writeFileSync(path.join(__dirname,'..','sections','data.js'),js);
console.log('boxes:',Object.keys(out.boxes).join(', ')||'(none)','· services:',out.services.length,'· nutrition:',out.nutrition.length,'·',(js.length/1024).toFixed(0),'KB');
